"""Command definitions for fresh acquisition and private work state."""
import argparse
from pathlib import Path

from .review_cli import configure


def arguments():
    parser = argparse.ArgumentParser(description="Fresh X collection; private data outside Git")
    parser.add_argument("--state", type=Path, required=True)
    commands = parser.add_subparsers(dest="command", required=True)
    video = commands.add_parser('prepare-video')
    video.add_argument('--account', required=True)
    video.add_argument('--source', required=True)
    video.add_argument('--package', type=Path, required=True)
    video.add_argument('--reason', required=True)
    command = commands.add_parser("collect")
    command.add_argument("kind", choices=("likes", "bookmarks"))
    command.add_argument("--max-requests", type=int, default=500)
    command.add_argument("--new-run", action="store_true")
    migration = commands.add_parser("migrate-quick")
    migration.add_argument("--apply", metavar="PREVIEW_DIGEST")
    repairs = commands.add_parser('recover-quick')
    repairs.add_argument('--apply', metavar='PREVIEW_DIGEST')
    retention = commands.add_parser('retain', help='preview derived-data retention; originals and canonical proofs are preserved')
    retention.add_argument('--apply', action='store_true', help='delete only eligible expired copies')
    commands.add_parser("status")
    commands.add_parser("queue")
    commands.add_parser("report")
    timings = commands.add_parser("policy-report")
    timings.add_argument("--run", dest="run_id", metavar="ID")
    batches = commands.add_parser("batches")
    batches.add_argument("--batch")
    configure(commands)
    recovery = commands.add_parser('recover')
    recovery.add_argument('source')
    recovery.add_argument('--reason', required=True)
    recovery.add_argument('--request-extra', type=int, choices=(0, 20), default=0)
    completion = commands.add_parser('complete-publication')
    completion.add_argument('publication')
    completion.add_argument('--reason', required=True)
    diagnosis = commands.add_parser('diagnose-publication')
    diagnosis.add_argument('publication')
    mapping = commands.add_parser('recover-wiki')
    mapping.add_argument('publication')
    mapping.add_argument('--reason', required=True)
    daily = commands.add_parser('configure-daily')
    daily.add_argument('--account', required=True)
    daily.add_argument('--chat', required=True)
    daily.add_argument('--timezone', required=True)
    research = commands.add_parser('research')
    research.add_argument('--approval', required=True)
    worker = commands.add_parser("work")
    worker.add_argument("--max-items", type=int, default=1)
    worker.add_argument("--lease-seconds", type=int, default=240)
    worker.add_argument('--defer-index', action='store_true')
    worker.add_argument('--unspent-only', action='store_true')
    commands.add_parser('index-pending')
    wiki = commands.add_parser("wiki")
    wiki.add_argument("--max-sources", type=int, default=5)
    wiki.add_argument("--audit", action="store_true", help="replay historical proof/artifact bytes without organizer calls")
    refresh = commands.add_parser('zk-refresh', help='explicit organization-only slice; no fact-check retries')
    refresh.add_argument('--publication', action='append', required=True)
    refresh.add_argument('--page', action='append', default=[], help='required existing note key')
    refresh.add_argument('--reason', required=True)
    grants = refresh.add_mutually_exclusive_group()
    grants.add_argument('--grant-extra-attempt', action='store_true', help='grant an exhausted selection its fourth attempt without models')
    grants.add_argument('--grant-fifth-attempt', action='store_true', help='record separate explicit approval for an exhausted selection fifth attempt')
    supervisor = commands.add_parser('supervise')
    supervisor.add_argument('--max-items', type=int, default=2)
    supervisor.add_argument('--max-sources', type=int, default=0)
    supervisor.add_argument('--seconds', type=int, default=1800)
    args = parser.parse_args()
    args.state = args.state.expanduser().resolve()
    return args
